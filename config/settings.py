def env_bool(name, default):
    value = os.environ.get(name)
    if value is None:
        return default
    return value.strip().lower() in {'1', 'true', 'yes', 'on'}


def env_list(name, default=()):
    return [
        item.strip()
        for item in os.environ.get(name, ','.join(default)).split(',')
        if item.strip()
    ]


